#!/usr/bin/env python3
"""Draws the Vita button symbols that replace the Classic Controller's
letters in the game's UI atlases (runtime/src/button_glyphs.cpp) as coverage
masks in the two disc sizes the atlases use: circle, cross, square and
triangle anti-aliased (8x supersampled, box-filtered), START and SELECT as
words in 3x5 pixel letters packed without gaps (the small disc's face is
15 px wide). Writes runtime/src/button_glyphs.inc; with --preview DIR also a
12x PNG of each.
"""
import argparse
import os

from PIL import Image, ImageDraw

SUPER = 8
# Mask size per disc size (the small disc's face is about 15 px wide, the
# large one's 19 px) and the box the symbols fill, as the letters do.
SIZES = {"small": 16, "large": 20}
SYMBOL = {"small": 12, "large": 15}

# 3x5 pixel letters; L and C are 2 wide.
LETTERS = {
    "S": [".##", "#..", ".#.", "..#", "##."],
    "T": ["###", ".#.", ".#.", ".#.", ".#."],
    "A": [".#.", "#.#", "###", "#.#", "#.#"],
    "R": ["##.", "#.#", "##.", "#.#", "#.#"],
    "E": ["###", "#..", "##.", "#..", "###"],
    "L": ["#.", "#.", "#.", "#.", "##"],
    "C": [".#", "#.", "#.", "#.", ".#"],
}


def word(text, size):
    rows = ["".join(LETTERS[c][y] for c in text) for y in range(5)]
    im = Image.new("L", (size, size), 0)
    x0, y0 = (size - len(rows[0])) // 2, (size - 4) // 2

    for y, row in enumerate(rows):
        for x, v in enumerate(row):
            if v == "#" and 0 <= x0 + x < size:
                im.putpixel((x0 + x, y0 + y), 255)

    return im


def draw(name, size):
    s = size * SUPER
    im = Image.new("L", (s, s), 0)
    d = ImageDraw.Draw(im)
    w = round(SUPER * (1.7 if size <= 12 else 2.0))  # stroke width, as the letters'
    e = SUPER * 0.5  # PIL's outlines grow inward from the box

    if name == "circle":
        d.ellipse((e, e, s - e, s - e), outline=255, width=w)
    elif name == "cross":
        a, b = SUPER * 1.6, s - SUPER * 1.6
        d.line((a, a, b, b), fill=255, width=w)
        d.line((a, b, b, a), fill=255, width=w)
    elif name == "square":
        i = SUPER * 1.3
        d.rectangle((i, i, s - i, s - i), outline=255, width=w)
    elif name == "triangle":
        d.polygon([(s / 2, e), (s - e, s - SUPER * 1.6), (e, s - SUPER * 1.6)], outline=255, width=w)

    return im.resize((size, size), Image.BOX)


def mask(name, kind):
    size = SIZES[kind]

    if name in ("start", "select"):
        return word(name.upper(), size)

    im = Image.new("L", (size, size), 0)
    symbol = draw(name, SYMBOL[kind])
    im.paste(symbol, ((size - symbol.size[0]) // 2, (size - symbol.size[1]) // 2))
    return im


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "runtime", "src", "button_glyphs.inc"))
    p.add_argument("--preview")
    args = p.parse_args()
    lines = ["// Generated by scripts/vita_button_glyphs.py: the Vita button symbols' coverage", "// masks (0-255), row by row.", ""]

    for name in ("circle", "cross", "square", "triangle", "start", "select"):
        for kind, size in SIZES.items():
            im = mask(name, kind)
            data = im.tobytes()
            lines.append(f"constexpr uint8_t k_{name}_{kind}[{size} * {size}] = {{")

            for y in range(size):
                lines.append("    " + ", ".join(str(v) for v in data[y * size:(y + 1) * size]) + ",")

            lines.append("};")
            lines.append("")

            if args.preview:
                os.makedirs(args.preview, exist_ok=True)
                im.resize((size * 12, size * 12), Image.NEAREST).save(os.path.join(args.preview, f"{name}_{kind}.png"))

    with open(args.out, "w") as f:
        f.write("\n".join(lines).rstrip() + "\n")


if __name__ == "__main__":
    main()
