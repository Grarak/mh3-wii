// WebGPU shader bank sources: writes the GLSL ES of every
// program stage the web build can ever bind, named by its runtime key, plus a
// manifest. scripts/web-shader-bank.py converts them to WGSL and embeds the
// result. Host tool; standard library and xxHash only.
//
//   mh3-web-shader-bank OUTPUT
//
// Keys match aurora-main/lib/webgpu: XXH3-64 of the ProgramDesc vertex and
// fragment text exactly as the GLES backend receives it (the native shading
// stages of runtime/src/native_shader_source.cpp and the fixed GLSL programs
// of aurora::gfx::fixed_shader_sources()). The backend's own programs (clear,
// present, native UI geometry) are WGSL in the backend and not in the bank.
#include "../runtime/src/native_shader_source.h"
#include "gfx/fixed_shader_sources.hpp"
#define XXH_INLINE_ALL
#include <xxhash.h>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <map>
#include <set>
#include <sstream>
#include <stdexcept>
#include <string>

namespace {
namespace fs = std::filesystem;

struct Stage {
    std::string glsl, kind, name;
};

// (stage letter, key) -> stage; 'v' vertex, 'f' fragment.
using Bank = std::map<std::pair<char, uint64_t>, Stage>;

std::string Hex(uint64_t key) {
    char text[17];
    std::snprintf(text, sizeof text, "%016llx", static_cast<unsigned long long>(key));
    return text;
}

uint64_t Key(const std::string& source) {
    return XXH3_64bits(source.data(), source.size());
}

void Add(Bank& bank, char stage, std::string glsl, std::string kind, std::string name) {
    const uint64_t key = Key(glsl);
    auto [it, inserted] = bank.try_emplace({stage, key}, Stage{glsl, kind, name});

    if (!inserted && it->second.glsl != glsl)
        throw std::runtime_error("Two shader bank sources share key " + Hex(key) + stage + ": " + it->second.name + ", " + name);
}

std::string Read(const fs::path& path) {
    std::ifstream file(path, std::ios::binary);

    if (!file)
        throw std::runtime_error("Cannot read " + path.string());

    std::ostringstream text;
    text << file.rdbuf();
    return text.str();
}

// Rewrites only changed files so the build's restat keeps later steps idle.
void Write(const fs::path& path, const std::string& text) {
    if (fs::exists(path) && Read(path) == text)
        return;

    const auto temporary = path.string() + ".tmp";
    {
        std::ofstream file(temporary, std::ios::binary | std::ios::trunc);

        if (!(file << text))
            throw std::runtime_error("Cannot write " + temporary);
    }

    fs::rename(temporary, path);
}
} // namespace

int main(int argc, char** argv) try {
    if (argc != 2) {
        std::fprintf(stderr, "usage: %s OUTPUT\n", argv[0]);
        return 2;
    }

    Bank bank;

    // The native material programs: the complete key domain of each stage.
    for (const auto& key : NativeShaderVertexKeys())
        Add(bank, 'v', NativeShaderGlslVertex(key), "shade", NativeShaderVertexName(key));

    for (const auto& key : NativeShaderFragmentKeys())
        Add(bank, 'f', NativeShaderGlslFragment(key), "shade", NativeShaderFragmentName(key));

    // The GLSL programs of the shared renderer modules, as their ProgramDesc has them.
    for (const auto& program : aurora::gfx::fixed_shader_sources()) {
        Add(bank, 'v', program.vertex, "fixed", program.label);
        Add(bank, 'f', program.fragment, "fixed", program.label);
    }

    const fs::path output = argv[1], glsl = output / "glsl";
    fs::create_directories(glsl);
    std::set<std::string> current;
    std::string manifest = "# key\tstage\tkind\tname (generated by mh3-web-shader-bank)\n";
    std::map<char, size_t> counts;

    for (const auto& [id, stage] : bank) {
        const auto file = Hex(id.second) + "_" + id.first + ".glsl";
        current.insert(file);
        Write(glsl / file, stage.glsl);
        manifest += Hex(id.second) + "\t" + id.first + "\t" + stage.kind + "\t" + stage.name + "\n";
        ++counts[id.first];
    }

    for (const auto& entry : fs::directory_iterator(glsl))
        if (!current.count(entry.path().filename().string()))
            fs::remove(entry.path());
    Write(output / "manifest.tsv", manifest);
    std::printf("WebGPU shader bank sources: %zu vertex, %zu fragment stages\n", counts['v'], counts['f']);
    return 0;
} catch (const std::exception& error) {
    std::fprintf(stderr, "mh3-web-shader-bank: %s\n", error.what());
    return 1;
}
